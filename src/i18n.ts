export function translate(
  language: Language,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  const message = (language === 'en' ? en : zh)[key]
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values?.[name] === undefined ? placeholder : String(values[name]))
}
